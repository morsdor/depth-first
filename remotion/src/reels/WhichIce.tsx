// where a point on the glass world lands on the 1080 x 1920 frame — the same camera and the same root group the scene uses
const projCam = (() => {
  const c = new THREE.PerspectiveCamera(FOV, REEL_W / REEL_H, 0.5, 4000);
  c.position.set(0, CAM_Y, CAM_Z);
  c.lookAt(0, LOOK_Y, 0);
  c.updateMatrixWorld();
  c.updateProjectionMatrix();
  return c;
})();
const projectLocalRaw = (t: number, p: [number, number, number]) => {
  const r = rigAt(t);
  const m = new THREE.Matrix4().compose(new THREE.Vector3(r.gx, r.gy, r.gz), new THREE.Quaternion().setFromEuler(new THREE.Euler(r.rx, r.ry, 0)), new THREE.Vector3(1, 1, 1));
  const v = new THREE.Vector3(...p).applyMatrix4(m).project(projCam);
  return { x: (v.x * 0.5 + 0.5) * REEL_W, y: (1 - (v.y * 0.5 + 0.5)) * REEL_H };
};
