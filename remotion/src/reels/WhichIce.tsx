type Zone = 'top' | 'bottom' | 'tag';
const BLOCK_STYLE: Record<string, { zone: Zone; size: number }> = {
  B01: { zone: 'top', size: 66 },
  B02: { zone: 'top', size: 56 },
  B03: { zone: 'top', size: 54 },
  B04: { zone: 'top', size: 58 },
  B05: { zone: 'top', size: 56 },
  B06: { zone: 'tag', size: 54 },
  B07: { zone: 'top', size: 56 },
  B08: { zone: 'bottom', size: 52 },
  B09: { zone: 'bottom', size: 52 },
  B10: { zone: 'bottom', size: 52 },
};

const TextBlock: React.FC<{ id: string }> = ({ id }) => {
  const b = BLOCKS.find((x) => x.id === id)!;
  const st = BLOCK_STYLE[id];
  const sentences = b.copy.split(/\.\s+/).map((x, i, arr) => (i < arr.length - 1 ? x : x.replace(/\.$/, '')) + (i < arr.length - 1 ? '' : '.'));
  // B07 carries a declaration, set small: the second sentence of the block
  const isDecl = id === 'B07';
  const pos: React.CSSProperties =
    st.zone === 'top'
      ? { top: SAFE_TOP + 22 }
      : st.zone === 'bottom'
      ? { bottom: REEL_H - SAFE_BOTTOM + 6 }
      : { top: SAFE_TOP + 22 };
  return (
    <Fade from={b.tIn * FPS} to={b.tOut * FPS} style={{ position: 'absolute', left: 60, width: 810, textAlign: 'center', textWrap: 'balance' as React.CSSProperties['textWrap'], ...pos }}>
      {isDecl ? (
        <>
          <div style={{ fontFamily: 'Archivo Black', fontSize: st.size, lineHeight: 1.1, letterSpacing: -1, color: INK }}>{sentences[0]}</div>
          <div style={{ fontFamily: 'IBM Plex Mono', fontWeight: 600, fontSize: 38, letterSpacing: 2, color: DIM, marginTop: 12 }}>{sentences.slice(1).join(' ')}</div>
        </>
      ) : (
        <div
          style={{
            fontFamily: 'Archivo Black', fontSize: st.size, lineHeight: 1.12, letterSpacing: -1, color: INK, textShadow: '0 2px 18px rgba(4,14,31,0.9)',
            ...(st.zone === 'tag' ? { display: 'inline-block', background: 'rgba(4,14,31,0.78)', padding: '10px 26px 14px', borderRadius: 16 } : {}),
          }}
        >
          {b.copy}
        </div>
      )}
    </Fade>
  );
};

