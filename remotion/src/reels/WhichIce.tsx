// ── helpers ───────────────────────────────────────────────────────────────
const clamp01 = (x: number) => Math.min(1, Math.max(0, x));
const sm = (t: number, w: readonly [number, number]) => {
  const x = clamp01((t - w[0]) / (w[1] - w[0]));
  return x * x * (3 - 2 * x);
};
const lerp = (a: number, b: number, k: number) => a + (b - a) * k;
/** The cube for a melt fraction, from the run's own curve (research/melt_check.py), interpolated between its 21 samples. */
const floatAt = (m: number) => {
  const c = FLOAT_CURVE;
  const x = clamp01(m) * (c.length - 1);
  const i = Math.min(c.length - 2, Math.floor(x));
  const f = x - i;
  return { level: lerp(c[i][1], c[i + 1][1], f), side: lerp(c[i][2], c[i + 1][2], f), draft: lerp(c[i][3], c[i + 1][3], f) };
};

// ── the glass world ───────────────────────────────────────────────────────────
const LEFT_X = -4.9;
const RIGHT_X = 4.9;
/** The safe column is centred at x = 465 (chrome.tsx SAFE_CX), not at the canvas centre 540: everything is built 75 px to the left of centre. */
const CENTER_SHIFT_PX = REEL_W / 2 - 465;
const pxToUnits = (px: number, d: number) => (px * 2 * d * Math.tan((FOV / 2) * (Math.PI / 180))) / REEL_H;

type Rig = { gx: number; gy: number; gz: number; rx: number; ry: number; rightX: number };

const CAM_Y = 5.0;
const CAM_Z = 17;
const LOOK_Y = 3.2;
const PITCH = Math.atan((CAM_Y - LOOK_Y) / CAM_Z); // the camera looks this far down
/** Where the group's origin must sit so the glasses' centre lands at `yPx` on a 1920 px frame, at distance `d` from the camera. */
const gyFor = (d: number, yPx: number) => {
  const alpha = Math.atan(((REEL_H / 2 - yPx) / (REEL_H / 2)) * Math.tan((FOV / 2) * (Math.PI / 180)));
  return CAM_Y + d * Math.tan(alpha - PITCH) - LOOK_Y;
};

/** The camera, as the root group: a glass, then two, then pulled out until the glass is a speck on the sea. */
const rigAt = (t: number): Rig => {
  const slide = sm(t, ANIM.slide);
  const pullU = sm(t, ANIM.pull);
  const holdU = clamp01((t - ANIM.slide[1]) / (ANIM.pull[0] - ANIM.slide[1]));
  // distance from the camera to the table centre, in world units
  const dSingle = lerp(27, 25.5, clamp01(t / ANIM.slide[0]));
  const dPair = lerp(35.5, 33.5, holdU);
  const dHold = lerp(dSingle, dPair, slide);
  const dEnd = 190;
  const d = t < ANIM.pull[0] ? dHold : dPair * Math.exp(Math.log(dEnd / dPair) * pullU);
  const yPx = lerp(lerp(1010, 880, slide), 760, pullU); // where the glasses' centre sits on the frame
  const gx = lerp(-LEFT_X * CM, 0, slide) * (1 - pullU) - pxToUnits(CENTER_SHIFT_PX, d);
  const ryOrbit = lerp(-0.3, 0.1, clamp01(t / ANIM.slide[0]));
  const ry = lerp(ryOrbit, lerp(0.04, -0.03, holdU), slide) * (1 - pullU);
  const rx = lerp(0.04, 0.34, pullU);
  // the shelf glass is not in the first shot: it is slid in as the camera pulls back, so it never shows at the edge of the single glass
  const rightX = RIGHT_X + 10 * (1 - sm(t, [ANIM.slide[0] - 0.4, ANIM.slide[1]]));
  return { gx, gy: gyFor(d, yPx), gz: CAM_Z - d, rx, ry, rightX };
};

const seeded = (seed: number) => () => ((seed = (seed * 16807) % 2147483647) / 2147483647);

type Floe = { x: number; z: number; w: number; d: number; rot: number; tone: number };
const makeFloes = (): Floe[] => {
  const r = seeded(97);
  const out: Floe[] = [];
  for (let i = 0; i < 70; i++) {
    const ang = r() * Math.PI * 2;
    const w = 2.5 + Math.pow(r(), 1.6) * 13;
    const rad = 14 + w * 0.8 + Math.pow(r(), 0.8) * 118;
    out.push({ x: Math.cos(ang) * rad, z: Math.sin(ang) * rad, w, d: w * (0.55 + r() * 0.6), rot: r() * Math.PI, tone: r() });
  }
  return out;
};
