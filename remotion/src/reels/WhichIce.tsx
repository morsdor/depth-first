// ── Greenland ───────────────────────────────────────────────────────────────
const R_EARTH_M = 6371000;
const unit = (lonDeg: number, latDeg: number) => {
  const l = (lonDeg * Math.PI) / 180;
  const p = (latDeg * Math.PI) / 180;
  return new THREE.Vector3(Math.cos(p) * Math.sin(l), Math.sin(p), Math.cos(p) * Math.cos(l));
};

const decodeHeights = (): Int16Array => {
  const bin = atob(GREENLAND_HEIGHTS_B64);
  const buf = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) buf[i] = bin.charCodeAt(i);
  return new Int16Array(buf.buffer);
};

const patchGeometry = (): THREE.BufferGeometry => {
  const h = decodeHeights();
  const { lon0, lon1, lat0, lat1, nLon, nLat } = GREENLAND;
  const pos = new Float32Array(nLon * nLat * 3);
  const uv = new Float32Array(nLon * nLat * 2);
  for (let i = 0; i < nLat; i++) {
    const lat = lat1 - (i * (lat1 - lat0)) / (nLat - 1);
    for (let j = 0; j < nLon; j++) {
      const lon = lon0 + (j * (lon1 - lon0)) / (nLon - 1);
      const r = 1 + (EXAG * h[i * nLon + j]) / R_EARTH_M;
      const u = unit(lon, lat).multiplyScalar(r);
      const k = i * nLon + j;
      pos[k * 3] = u.x;
      pos[k * 3 + 1] = u.y;
      pos[k * 3 + 2] = u.z;
      uv[k * 2] = (lon - lon0) / (lon1 - lon0);
      uv[k * 2 + 1] = (lat - lat0) / (lat1 - lat0);
    }
  }
  const idx: number[] = [];
  for (let i = 0; i < nLat - 1; i++) {
    for (let j = 0; j < nLon - 1; j++) {
      const a = i * nLon + j;
      idx.push(a, a + nLon, a + 1, a + 1, a + nLon, a + nLon + 1);
    }
  }
  const g = new THREE.BufferGeometry();
  g.setAttribute('position', new THREE.BufferAttribute(pos, 3));
  g.setAttribute('uv', new THREE.BufferAttribute(uv, 2));
  g.setIndex(idx);
  g.computeVertexNormals();
  return g;
};

/** Soft edges, so the patch does not read as a rectangle pasted on a sphere. */
const edgeFade = (): THREE.CanvasTexture => {
  const c = document.createElement('canvas');
  c.width = c.height = 128;
  const g = c.getContext('2d')!;
  const img = g.createImageData(128, 128);
  for (let y = 0; y < 128; y++) {
    for (let x = 0; x < 128; x++) {
      const e = Math.min(x, 127 - x, y, 127 - y) / 127;
      const a = clamp01(e / 0.1);
      const k = Math.round(255 * a * a * (3 - 2 * a));
      const i = (y * 128 + x) * 4;
      img.data[i] = img.data[i + 1] = img.data[i + 2] = k;
      img.data[i + 3] = 255;
    }
  }
  g.putImageData(img, 0, 0);
  return new THREE.CanvasTexture(c);
};

type PlanetPose = { D: number; tilt: number; lon: number; lat: number; shiftY: number };
const planetPose = (t: number): PlanetPose => {
  // a long swoop: the whole island from high up, then down and low over the sea, looking along the ice sheet's edge
  const t0 = ANIM.greenland_in[0] - 0.4;
  const u = clamp01((t - t0) / (ANIM.house_in[1] - t0));
  const e = u * u * (3 - 2 * u);
  return {
    D: Math.exp(lerp(Math.log(1.9), Math.log(0.5), e)),
    tilt: lerp(0.1, 1.26, e),
    lon: lerp(-41, -37, e),
    lat: lerp(71.5, 67.6, e),
    shiftY: lerp(0, -0.01, e),
  };
};

