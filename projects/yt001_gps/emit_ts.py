"""Pack the simulation output, the real sentence timings and the land polygons into TypeScript, and
REFUSE to write if a claim the narration or the screen makes is not true of the data.

  remotion/src/yt/data/gps.ts    timeline, numbers, solver iterates, 2D demo, satellite slots
  remotion/src/yt/data/land.ts   Natural Earth 110m land (public domain), rounded to 0.1 degree
  projects/yt001_gps/captions.srt  sentence-level captions straight from the timeline
"""
import json
import math
from pathlib import Path

HERE = Path(__file__).parent
REPO = HERE.parents[1]
OUT = REPO / "remotion" / "src" / "yt" / "data"
OUT.mkdir(parents=True, exist_ok=True)

N = json.loads((HERE / "sims" / "numbers.json").read_text())
D = json.loads((HERE / "sims" / "gps_data.json").read_text())
TL = json.loads((HERE / "timeline.json").read_text())

fails = []
def claim(text, ok):
    print(("  ok   " if ok else "  FAIL ") + text)
    if not ok:
        fails.append(text)

# ── claims the copy and the screen share with the data ─────────────────────
claim("31 satellites drawn = the 31 the narration says", len(D["sats31"]) == 31)
claim("orbit altitude computed from Kepler is 'about 20,200 km' (20,100-20,300)", 20100 < N["alt_km"] < 20300)
claim("period is 11 h 58 min (11.95-11.99 h)", 11.95 < N["period_h"] < 11.99)
claim("'nearly four km/s' (3.8-3.95)", 3.8 < N["v_kms"] < 3.95)
claim("overhead delay says 'sixty-seven' ms", round(N["overhead_ms"]) == 67)
claim("SR 'seven', GR 'forty-six', net 'thirty-eight and a half' (38.3-38.8)",
      round(-N["sr_us_day"]) == 7 and round(N["gr_us_day"]) == 46 and 38.3 <= N["net_us_day"] <= 38.8)
claim("net distance says 'eleven and a half' km (11.3-11.7)", 11.3 <= N["net_km_day"] <= 11.7)
claim("computed offset reproduces the published 10.22999999543 MHz", N["set_mhz_str"].startswith("10.2299999954"))
claim("computed offset is within 1 ppt of NTS-2's prediction 446.5", abs(N["frac_ppt"] - 446.5) < 1.0)
claim("NTS-2 measured vs predicted agree within 1% (442.5 vs 446.5)", abs(442.5 - 446.5) / 446.5 < 0.01)
claim("solver narration says '%s' steps = %d iterates" % (N["iters_words"], N["iters"]), len(D["fix"]["iters"]) - 1 == N["iters"])
claim("solver ends within 'a few metres' (< 6 m) with 2 m noise per range", D["fix"]["iters"][-1]["pos_err_m"] < 6.0)
claim("clock error recovered to 15 m of range", abs(N["b_est_ms"] - N["b_true_ms"]) * 1e-3 * 299792458 < 15)
claim("'at least four above the horizon' holds on the global grid (24-sat baseline, 5 deg mask)",
      N["visibility_24_walker_5deg"]["min"] >= 4)
claim("1 microsecond = 300 m", abs(N["us_m"] - 300) < 1)
claim("scene order is the one the visuals assume",
      [s["id"] for s in TL["scenes"]] == ["hook", "satellites", "ranging", "clock", "einstein", "accuracy", "close"])
dur = TL["duration"]
claim("runtime is about five and a half minutes (300-345 s) incl. a 10 s credits tail, got %.1f s" % dur, 300 <= dur <= 345)
claim("'about a fifteenth of a second' overhead delay (1/15 s = 66.7 ms; ours %.1f ms)" % N["overhead_ms"], abs(1000 / N["overhead_ms"] - 15) < 0.5)
claim("'about fifty times higher than the space station' (alt / 420 km = %.0f)" % (N["alt_km"] / 420), 45 <= N["alt_km"] / 420 <= 52)
claim("'three seconds, about a kilometre' for thunder (343 m/s x 3 s = %.0f m)" % (343 * 3), 1000 <= 343 * 3 <= 1100)
claim("'a few billionths of a megahertz': 10.23 - 10.22999999543 = %.2e MHz" % (10.23 - 10.22999999543), 1e-9 < 10.23 - 10.22999999543 < 1e-8)
claim("'less than one percent apart' (442.5 vs 446.5)", abs(442.5 - 446.5) / 446.5 < 0.01)

# the screen must not name a figure before the voice does: the ledger rows in 'einstein' are keyed to sentence cues
es = [s for s in TL["sentences"] if s["scene"] == "einstein"]
claim("einstein scene has the 8 sentences the visuals are keyed to", len(es) == 8)

if fails:
    raise SystemExit("REFUSING to write: %d claim(s) false" % len(fails))

# ── land ───────────────────────────────────────────────────────────────────
gj = json.loads(Path("/tmp/ne_110m_land.geojson").read_text())
rings = []
for f in gj["features"]:
    g = f["geometry"]
    polys = g["coordinates"] if g["type"] == "MultiPolygon" else [g["coordinates"]]
    for poly in polys:
        rings.append([[round(x, 1), round(y, 1)] for x, y in poly[0]])      # outer ring only
(OUT / "land.ts").write_text(
    "// GENERATED by projects/yt001_gps/emit_ts.py — Natural Earth 110m land (public domain). Do not edit.\n"
    "export const LAND: number[][][] = " + json.dumps(rings, separators=(",", ":")) + ";\n")

# ── the data module ────────────────────────────────────────────────────────
payload = {
    "timeline": TL,
    "numbers": N,
    "orbit": D["orbit"],
    "sats31": D["sats31"],
    "fix": D["fix"],
    "demo2d": D["demo2d"],
}
(OUT / "gps.ts").write_text(
    "// GENERATED by projects/yt001_gps/emit_ts.py — every figure here came out of sims/gps_sims.py. Do not edit.\n"
    "export const GPS = " + json.dumps(payload, separators=(",", ":")) + " as const;\n"
    "export type Gps = typeof GPS;\n")

# ── captions ───────────────────────────────────────────────────────────────
def ts(t):
    h, r = divmod(t, 3600)
    m, s = divmod(r, 60)
    return "%02d:%02d:%02d,%03d" % (h, m, int(s), round((s - int(s)) * 1000) % 1000)
lines = []
for i, s in enumerate(TL["sentences"], 1):
    lines += [str(i), f"{ts(s['start'])} --> {ts(s['end'])}", s["text"], ""]
(HERE / "captions.srt").write_text("\n".join(lines))
print(f"wrote gps.ts, land.ts ({len(rings)} rings), captions.srt ({len(TL['sentences'])} cues); runtime {dur:.1f}s")
